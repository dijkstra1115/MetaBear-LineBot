# Writes the coin flips every figure in the film comes from: 1,000 players, 100 flips each, Python's
# random.Random(0) in the same draw order as the script that produced the narration's numbers.
# The film recomputes wealth from these flips (assets/js/model.js), so all-in and Kelly use the same flips.
# Usage (from the project folder): python -I scripts/sim.py  → assets/data/sim.js
import json, os, random
r = random.Random(0)
flips = [[r.random() < 0.5 for _ in range(1000)] for _ in range(100)]
rows = ["".join("1" if h else "0" for h in row) for row in flips]
os.makedirs("assets/data", exist_ok=True)
open("assets/data/sim.js", "w").write("// Generated by scripts/sim.py (random.Random(0)); 1 = heads. flips[round][player].\nwindow.SIM = " + json.dumps({"players": 1000, "rounds": 100, "flips": rows}) + ";\n")
print("ok")
