// Builds the generated parts of the film from its sources:
//   assets/js/world.js          src/world-src.js bundled with Three.js (classic script, no network)
//   compositions/captions.html  every caption group and subtitle line, timed from assets/data/timeline.json
//   assets/fonts/NotoSansTC-sub.ttf  Noto Sans TC cut to the Chinese characters the film uses
//   assets/data/beats.json      the narration cue times, for scripts/score.py
// Usage (from the project folder): node scripts/build.mjs
import { build } from "esbuild";
import { readFileSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import vm from "node:vm";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const REPO = resolve(ROOT, "../../..");

await build({
  entryPoints: [join(ROOT, "src/world-src.js")],
  bundle: true,
  format: "iife",
  target: "es2020",
  outfile: join(ROOT, "assets/js/world.js"),
  nodePaths: [join(REPO, "node_modules")],
  banner: { js: "// Generated by scripts/build.mjs from src/world-src.js and three; do not edit." },
  logLevel: "warning",
});

// ---- beat times for scripts/score.py (the same cue module the picture uses)
{
  const ctx = { window: {} };
  vm.createContext(ctx);
  for (const f of ["assets/data/timeline.js", "assets/js/beats.js"]) vm.runInContext(readFileSync(join(ROOT, f), "utf8"), ctx);
  writeFileSync(join(ROOT, "assets/data/beats.json"), JSON.stringify(ctx.window.BEATS, null, 1));
}

// ---- captions
const TL = JSON.parse(readFileSync(join(ROOT, "assets/data/timeline.json"), "utf8"));
const esc = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
const groups = [];
const lines = [];
const allLines = TL.chunks.flatMap((c) => c.lines);
allLines.forEach((line, li) => {
  const nextLine = allLines[li + 1];
  const lineEnd = nextLine ? Math.min(line.end + 0.55, nextLine.start - 0.06) : line.end + 2.4;
  lines.push({ start: Math.max(0.1, line.start - 0.12), end: lineEnd, zh: line.zh });
  // Groups of up to 5 words / 24 characters, broken after punctuation.
  let cur = [];
  const flush = () => cur.length && groups.push(cur) && (cur = []);
  for (const tk of line.tokens) {
    const len = cur.reduce((a, t) => a + t.text.length + 1, 0);
    if (cur.length && (cur.length >= 5 || len + tk.text.length > 24)) flush();
    cur.push(tk);
    if (/[.,:;?!”]$/.test(tk.text)) flush();
  }
  flush();
  groups[groups.length - 1].lineEnd = lineEnd;
});
let html = "";
groups.forEach((g, gi) => {
  const next = groups[gi + 1];
  const start = Math.max(0.1, g[0].start - 0.06);
  const end = g.lineEnd !== undefined ? g.lineEnd : Math.max(g[g.length - 1].end + 0.05, next ? next[0].start - 0.06 : 0);
  const words = g
    .map((t, wi) => `<span id="cw-${gi}-${wi}" class="w${t.key ? " k" : ""}" data-t="${(t.start - start).toFixed(3)}">${esc(t.text)}${t.key ? '<i class="box"><i class="h a"></i><i class="h b"></i><i class="h c"></i><i class="h d"></i></i>' : ""}</span>`)
    .join(" ");
  html += `      <div id="cg-${gi}" class="clip cg" data-start="${start.toFixed(3)}" data-duration="${(end - start).toFixed(3)}" data-track-index="0"><div class="cg-in"><span class="pl">${words}</span></div></div>\n`;
});
lines.forEach((l, i) => {
  html += `      <div id="cz-${i}" class="clip cz" data-start="${l.start.toFixed(3)}" data-duration="${(l.end - l.start).toFixed(3)}" data-track-index="1"><div class="cz-in"><span class="pl">${esc(l.zh)}</span></div></div>\n`;
});
const tpl = readFileSync(join(ROOT, "scripts/captions.template.html"), "utf8");
writeFileSync(join(ROOT, "compositions/captions.html"), tpl.replace("<!--GROUPS-->", html.trimEnd()).replace(/__DURATION__/g, String(TL.duration)));

// ---- Chinese font subset
const chars = new Set();
for (const l of lines) for (const ch of l.zh) chars.add(ch);
for (const f of ["compositions/share.html", "compositions/world.html"]) for (const ch of readFileSync(join(ROOT, f), "utf8")) if (ch.charCodeAt(0) > 0x2e80) chars.add(ch);
"0123456789%$+−-×÷.,，。、：？！「」（）·".split("").forEach((c) => chars.add(c));
writeFileSync(join(ROOT, "scripts/.chars.txt"), [...chars].join(""));
execFileSync("pyftsubset", [join(REPO, "motion/flow-arena/promo/scripts/font-src/NotoSansTC-full.ttf"), `--text-file=${join(ROOT, "scripts/.chars.txt")}`, `--output-file=${join(ROOT, "assets/fonts/NotoSansTC-sub.ttf")}`, "--layout-features=*"]);
console.log(`world.js bundled · ${groups.length} caption groups · ${lines.length} subtitle lines · ${chars.size} CJK chars`);
