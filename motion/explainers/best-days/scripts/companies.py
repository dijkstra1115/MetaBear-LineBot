TICKERS = sorted({t for era in ERAS for t, _, _ in era["list"]})

if "--fetch" in sys.argv:
    import yfinance as yf

    df = yf.download(TICKERS, period="max", interval="1d", auto_adjust=True, progress=False)["Close"]
    df.resample("W-FRI").last().to_csv(CSV)

weekly = pd.read_csv(CSV, index_col=0, parse_dates=True)
d0 = pd.Timestamp("1949-01-01")
series = {}
for t in TICKERS:
    s = weekly[t].dropna()
    if s.empty:
        print("no data", t)
        continue
    # week number = days since 1949-01-01 // 7, keyed by the Friday that ends the week
    w0 = int((s.index[0] - d0).days // 7)
    full = s.reindex(pd.date_range(s.index[0], s.index[-1], freq="W-FRI")).ffill()
    vals = [float(f"{v:.4g}") for v in full.values]
    series[t] = {"w0": w0, "c": vals}
    print(f"{t:6s} from {s.index[0].date()}  {len(vals)} weeks")

data = {
    "eras": [{"from": e["from"], "label": e["label"], "list": [{"t": t, "w": w, "zh": z} for t, w, z in e["list"]]} for e in ERAS],
    "series": series,
}
OUT.write_text(
    "// Generated by scripts/companies.py from assets/data/companies-weekly.csv (Yahoo Finance, adjusted weekly closes). Do not edit.\n"
    "window.COS = " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n",
    encoding="utf-8",
)
