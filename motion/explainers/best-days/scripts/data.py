"""S&P 500 daily closes -> assets/js/data.js, the one data module every figure in the film reads.

Usage (from this folder):
    python -I scripts/data.py            # uses assets/data/gspc.csv
    python -I scripts/data.py --fetch    # refreshes the CSV from Yahoo Finance (^GSPC) first

Definitions (also printed on screen in the end card):
- daily move = close / previous close - 1
- drawdown   = previous close / highest close so far - 1 (the state the day started in)
- 200-day    = mean of the 200 closes before the day
- top / worst 20 = ranked over every trading day from 1950-01-03 to the last close
"""

import json
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
CSV = ROOT / "assets/data/gspc.csv"
OUT = ROOT / "assets/js/data.js"
START = "1950-01-01"

if "--fetch" in sys.argv:
    import yfinance as yf

    df = yf.download("^GSPC", period="max", interval="1d", auto_adjust=False, progress=False)
    df["Close"].squeeze().dropna().rename("Close").to_csv(CSV)

close = pd.read_csv(CSV, index_col=0, parse_dates=True).squeeze().dropna()
# The all-time high counts from 1928, so 1950-54 still sit under the 1929 peak.
prev = close.shift(1)
ret = close / prev - 1
dd = prev / prev.cummax() - 1
ma200 = close.rolling(200).mean().shift(1)

frame = pd.DataFrame({"c": close, "ret": ret, "dd": dd, "ma": ma200, "prev": prev}).dropna()
frame = frame[frame.index >= "1949-01-01"]
film = frame[frame.index >= START]
first = frame.index.get_loc(film.index[0])


def peak_date(day):
    upto = close[: day - pd.Timedelta(days=1)]
    return upto.idxmax()


def row(day, rank):
    r = frame.loc[day]
    return {
        "i": int(frame.index.get_loc(day)),
        "d": day.strftime("%Y.%m.%d"),
        "ret": round(float(r.ret) * 100, 2),
        "dd": round(float(r.dd) * 100, 1),
        "ma": round(float(r.prev / r.ma - 1) * 100, 1),
        "peak": peak_date(day).strftime("%Y.%m.%d"),
        "rank": rank,
    }


top = [row(d, k + 1) for k, d in enumerate(film.nlargest(20, "ret").index)]
worst = [row(d, k + 1) for k, d in enumerate(film.nsmallest(20, "ret").index)]
worst_days = {w["i"] for w in worst}
tdays = list(frame.index)
for t in top:
    day = tdays[t["i"]]
    t["nearWorst"] = any(abs((tdays[w] - day).days) <= 14 for w in worst_days)

years = film["c"].resample("YE").last()
year_open = close[close.index < "1950-01-01"].iloc[-1]
yr = []
last = year_open
for y, v in years.items():
    yr.append({"y": y.year, "ret": round(float(v / last - 1) * 100, 1)})
    last = v

stats = {
    "below200": sum(t["ma"] < 0 for t in top),
    "bear": sum(t["dd"] <= -20 for t in top),
    "nearWorst": sum(t["nearWorst"] for t in top),
    "baseBelow200": round(float((film.prev < film.ma).mean()) * 100),
    "baseBear": round(float((film.dd <= -0.2).mean()) * 100),
    "days": len(film),
    "first": film.index[0].strftime("%Y.%m.%d"),
    "last": film.index[-1].strftime("%Y.%m.%d"),
}

days0 = pd.Timestamp("1949-01-01")
data = {
    "first": first,
    # highest close before the data starts (1929.09.16), so the film's running high matches dd
    "peak0": round(float(close[close.index < frame.index[0]].max()), 2),
    "peak0d": close[close.index < frame.index[0]].idxmax().strftime("%Y.%m.%d"),
    "day": [int((d - days0).days) for d in frame.index],
    "c": [round(float(v), 2) for v in frame.c],
    "ma": [round(float(v), 2) for v in frame.ma],
    "top": top,
    "worst": worst,
    "years": yr,
    "stats": stats,
}
OUT.write_text(
    "// Generated by scripts/data.py from assets/data/gspc.csv (Yahoo Finance ^GSPC). Do not edit.\n"
    "window.SPX = " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n",
    encoding="utf-8",
)
print(json.dumps(stats, ensure_ascii=False))
for t in top:
    print(t)
print(f"wrote {OUT} ({OUT.stat().st_size // 1024} KB)")
