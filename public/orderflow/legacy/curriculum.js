curriculum.forEach((course, index) => {
  course.number = index + 1;
  // The final result leads directly to the checkpoint. Do not make learners
  // advance through an identical scene just to reveal a question below it.
  if (course.steps?.length > 1) {
    const previous = course.steps.at(-2);
    const final = course.steps.at(-1);
    if (
      !previous.ops.length &&
      !previous.prediction &&
      previous.view === final.view &&
      previous.reveal === final.reveal
    ) {
      course.steps.pop();
    }
  }
  if (!course.quiz) return;
  const shift = index % course.quiz.options.length;
  course.quiz.options = course.quiz.options
    .slice(shift)
    .concat(course.quiz.options.slice(0, shift));
  course.quiz.answer =
    (course.quiz.options.length - shift) % course.quiz.options.length;
});
export const courseById = (id) =>
  curriculum.find((course) => course.id === id) || curriculum[0];
