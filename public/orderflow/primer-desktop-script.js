export function desktopNarrativeAt(scene, elapsed, reduced) {
  const { time } = scenePosition(scene, elapsed, reduced);
  const [headline, cues] = beats[scene];
  return {
    headline,
    question: cues.findLast(([at]) => at <= time)?.[1] ?? cues[0][1],
  };
}
