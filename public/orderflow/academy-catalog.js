export const isAvailable = (course) => course.status !== "planned";
export const courseById = (id) => courses.find((course) => course.id === id);
export const statusLabel = (course) =>
  ({
    ready: "可觀看",
    new: course.revision ? "本次重修" : "本次新課",
    planned: course.phase ?? "規劃中",
  })[course.status];
export const durationLabel = (seconds) =>
  seconds >= 90
    ? `約 ${Math.round(seconds / 6) / 10} 分`
    : `${Math.round(seconds)} 秒`;

export function selectCourses({ view = "ready", query = "", path = "" } = {}) {
  const route = paths.find((p) => p.id === path);
  const text = query.trim().toLocaleLowerCase();
  const selected = courses.filter(
    (course) =>
      (!route || route.ids.includes(course.id)) &&
      (view === "all" ||
        (view === "new" ? course.status === "new" : isAvailable(course))) &&
      (!text ||
        `${course.title} ${course.subtitle} ${course.description}`
          .toLocaleLowerCase()
          .includes(text)),
  );
  return route
    ? selected.sort((a, b) => route.ids.indexOf(a.id) - route.ids.indexOf(b.id))
    : selected;
}
